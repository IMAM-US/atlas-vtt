import { afterEach, expect, it, vi } from 'vitest';
import { createInMemoryApp } from '../mocks/inMemoryVault';
import { createViewAtlasStore } from '../../src/app/storeFactory';
import { getHistoryStore, runUntracked } from '../../src/app/stores/history';
import { AssetService } from '../../src/app/services/AssetService';
import { buildRecordedScene } from '../../src/app/agent-workspace/buildRecordedScene';
import { foundationRecording } from '../../src/app/agent-workspace/foundationRecording';
import { recordedSceneBindings } from '../../src/app/agent-workspace/recordedSceneBindings';

afterEach(() => vi.unstubAllGlobals());

it('edits, undoes, redoes and reopens native scene content without changing recorded identities or facts', async () => {
  const fetch = vi.fn(() => { throw new Error('This recorded scene must not contact a runtime'); });
  vi.stubGlobal('fetch', fetch);
  const websocket = vi.fn(() => { throw new Error('No live OpenRig connection'); });
  const events = vi.fn(() => { throw new Error('No live OpenRig subscription'); });
  vi.stubGlobal('WebSocket', websocket);
  vi.stubGlobal('EventSource', events);
  const path = 'atlas-vtt/collections/Default/scenes/Workspace.atlasmap';
  const memory = createInMemoryApp();
  const assets = AssetService.getInstance(memory.app);
  await assets.initialize();
  const seed = buildRecordedScene(assets.getCollectionSettings(assets.getDefaultCollectionId()));
  memory.files.set(path, JSON.stringify(seed));
  const factsBefore = JSON.stringify(foundationRecording);
  const open = async (id: string): Promise<ReturnType<typeof createViewAtlasStore>> => {
    const store = createViewAtlasStore(memory.app, id);
    store.getState().setPersistenceEnabled(false);
    store.getState().setMapPath(path);
    await store.persist.rehydrate();
    store.getState().setPersistenceEnabled(true);
    getHistoryStore(store)!.getState().clear();
    return store;
  };
  const store = await open('recorded-edit');
  const token = Object.values(store.getState().objects.tokens)[0]!;
  const card = Object.values(store.getState().objects.texts).find(text => text.recordingReference?.kind === 'work')!;
  const bindings = (): unknown => recordedSceneBindings(foundationRecording,
    [...Object.values(store.getState().objects.tokens), ...Object.values(store.getState().objects.texts)]);
  const referencesBefore = bindings();
  store.getState().setSelection([token.id]);
  store.getState().moveToken(token.id, 420, 350);
  store.getState().moveText(card.id, 140, 560);
  store.getState().updateText(card.id, { text: 'My authored working area' });
  const noteId = store.getState().addText({ x: 200, y: 1200, text: 'Owner annotation', fontSize: 24, fontFamily: 'sans-serif', color: '#fff' });
  const history = getHistoryStore(store)!;
  expect(history.getState().pastStates).toHaveLength(4);
  history.getState().undo();
  expect(store.getState().objects.texts[noteId]).toBeUndefined();
  history.getState().undo();
  expect(store.getState().objects.texts[card.id]!.text).toBe(card.text);
  history.getState().undo();
  expect(store.getState().objects.texts[card.id]).toMatchObject({ x: card.x, y: card.y });
  history.getState().undo();
  expect(store.getState().objects.tokens[token.id]).toMatchObject({ x: token.x, y: token.y });
  expect(bindings()).toEqual(referencesBefore);
  for (let step = 0; step < 4; step++) history.getState().redo();
  expect(store.getState().objects.tokens[token.id]).toMatchObject({ x: 420, y: 350, recordingReference: token.recordingReference });
  expect(store.getState().objects.texts[card.id]).toMatchObject({ x: 140, y: 560, text: 'My authored working area', recordingReference: card.recordingReference });
  await store.flushStorage();
  const saved = JSON.parse(memory.files.get(path)!);
  expect(saved.state.objects.texts[noteId].text).toBe('Owner annotation');
  const reopened = await open('recorded-reopen');
  expect(reopened.getState().objects).toEqual(store.getState().objects);
  expect(JSON.stringify(foundationRecording)).toBe(factsBefore);
  expect(fetch).not.toHaveBeenCalled();
  expect(websocket).not.toHaveBeenCalled();
  expect(events).not.toHaveBeenCalled();
  await reopened.flushStorage();
  runUntracked(store, () => store.getState().setPersistenceEnabled(false));
  runUntracked(reopened, () => reopened.getState().setPersistenceEnabled(false));
});

it('duplicates and deletes representations through native history without duplicating their recorded resource', async () => {
  const memory = createInMemoryApp();
  const assets = AssetService.getInstance(memory.app);
  await assets.initialize();
  const seed = buildRecordedScene(assets.getCollectionSettings(assets.getDefaultCollectionId()));
  const store = createViewAtlasStore(memory.app, 'recorded-representation-journey');
  store.getState().setPersistenceEnabled(false);
  runUntracked(store, () => store.setState(seed.state));
  const original = Object.values(store.getState().objects.tokens)[0]!;
  const factsBefore = JSON.stringify(foundationRecording);
  const history = getHistoryStore(store)!;
  history.getState().clear();
  const [copyId] = store.getState().duplicateMapObjects([original.id]);
  expect(copyId).not.toBe(original.id);
  const copy = store.getState().objects.tokens[copyId!]!;
  expect(copy.recordingReference).toEqual(original.recordingReference);
  expect([copy.x, copy.y]).not.toEqual([original.x, original.y]);
  expect(store.getState().selectedIds).toEqual([copyId]);
  expect(history.getState().pastStates).toHaveLength(1);
  store.getState().deleteSelected();
  expect(store.getState().objects.tokens[copyId!]).toBeUndefined();
  expect(store.getState().objects.tokens[original.id]).toEqual(original);
  history.getState().undo();
  expect(store.getState().objects.tokens[copyId!]!.recordingReference).toEqual(original.recordingReference);
  history.getState().undo();
  expect(store.getState().objects.tokens[copyId!]).toBeUndefined();
  history.getState().redo();
  expect(store.getState().objects.tokens[copyId!]!.recordingReference).toEqual(original.recordingReference);
  store.getState().setMapPath('atlas-vtt/collections/Default/scenes/Representations.atlasmap');
  store.getState().setPersistenceEnabled(true);
  await store.flushStorage();
  const reopened = createViewAtlasStore(memory.app, 'reopened-representations');
  reopened.getState().setPersistenceEnabled(false);
  reopened.getState().setMapPath(store.getState().mapPath);
  await reopened.persist.rehydrate();
  const representations = [original.id, copyId!].map(id => reopened.getState().objects.tokens[id]!);
  expect(new Set(representations.map(object => object.id)).size).toBe(2);
  expect(new Set(representations.map(object => object.recordingReference!.id)).size).toBe(1);
  expect(JSON.stringify(foundationRecording)).toBe(factsBefore);
});
